CREATE TABLE IF NOT EXISTS documents (scope TEXT NOT NULL, id TEXT NOT NULL, body TEXT NOT NULL, PRIMARY KEY(scope,id));
CREATE TABLE IF NOT EXISTS versions (scope TEXT PRIMARY KEY, rev INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS revision_checks (scope TEXT NOT NULL, expected INTEGER NOT NULL);
CREATE TRIGGER IF NOT EXISTS check_revision BEFORE INSERT ON revision_checks BEGIN
 SELECT CASE WHEN COALESCE((SELECT rev FROM versions WHERE scope=NEW.scope),0) <> NEW.expected THEN RAISE(ABORT,'revision-conflict') END;
END;
CREATE TABLE IF NOT EXISTS blobs (id TEXT PRIMARY KEY, owner TEXT NOT NULL, mime TEXT NOT NULL, size INTEGER NOT NULL, created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS blobs_owner ON blobs(owner);
CREATE TABLE IF NOT EXISTS blob_parts (id TEXT NOT NULL REFERENCES blobs(id) ON DELETE CASCADE, part INTEGER NOT NULL, bytes BLOB NOT NULL, PRIMARY KEY(id,part));
CREATE TABLE IF NOT EXISTS rate_limits (key TEXT PRIMARY KEY,hits INTEGER NOT NULL,expires INTEGER NOT NULL);
CREATE TRIGGER IF NOT EXISTS cap_blob_total BEFORE INSERT ON blobs BEGIN
 SELECT CASE WHEN COALESCE((SELECT SUM(size) FROM blobs),0)+NEW.size>104857600 THEN RAISE(ABORT,'site-media-full') END;
 SELECT CASE WHEN COALESCE((SELECT SUM(size) FROM blobs WHERE owner=NEW.owner),0)+NEW.size>20971520 THEN RAISE(ABORT,'user-media-full') END;
END;
